"""Turn forced-alignment output into caption chunks for the Amsterdam video.

Inputs : words.json   ([[word, start, end], ...] from pocketsphinx align)
         silences.txt (ffmpeg silencedetect lines) to snap word edges to pauses
         script.txt   (the exact voice-over script, for display text/punctuation)
Output : src/amsterdam/timing.ts
"""
import json, re, sys

words_path, sil_path, script_path, out_path = sys.argv[1:5]
CONFIG = json.load(open(sys.argv[5])) if len(sys.argv) > 5 else None
aligned = json.load(open(words_path))
sil = []
cur = None
for line in open(sil_path):
    k, v = line.split(":")
    v = float(v)
    if k.strip() == "silence_start":
        cur = v
    else:
        sil.append((cur if cur is not None else 0.0, v))
        cur = None

def snap(t, is_start):
    for a, b in sil:
        if a <= t <= b:
            return b if is_start else a
    return t

timed = []
for w, s, e in aligned:
    s2, e2 = snap(s, True), snap(e, False)
    if e2 <= s2:
        s2, e2 = s, e
    timed.append([re.sub(r"\(\d+\)", "", w), round(s2, 3), round(e2, 3)])

# display tokens straight from the script (keep punctuation)
disp = open(script_path).read().split()
NUMBER_SPANS = {
    ("fourteen", "fifty-two,"): "1452,",
    ("twelve", "meters"): "12 meters",
    ("thirteen", "thousand,", "six", "hundred", "and", "fifty-nine"): "13,659",
}
if CONFIG:
    NUMBER_SPANS = {tuple(k.split("|")): v for k, v in CONFIG["spans"].items()}
tokens = []  # (display, n_aligned_words)
i = 0
while i < len(disp):
    matched = False
    for span, text in NUMBER_SPANS.items():
        if tuple(x.lower() for x in disp[i : i + len(span)]) == span:
            n = sum(len([p for p in x.replace("-", " ").split() if re.sub(r"[^a-z']", "", p.lower())]) for x in span)
            tokens.append((text, n))
            i += len(span)
            matched = True
            break
    if not matched:
        tokens.append((disp[i], len([p for p in disp[i].replace("-", " ").split() if re.sub(r"[^a-z']", "", p.lower())])))
        i += 1

words = []
k = 0
for text, n in tokens:
    seg = timed[k : k + n]
    words.append({"text": text, "start": seg[0][1], "end": seg[-1][2]})
    k += n
assert k == len(timed), (k, len(timed))

HL_DEFAULT = {
    "swamp", "sinks", "sink", "sand", "mud", "wooden", "burns", "fire", "1452", "brick", "heavy", "cracks",
    "hard", "12 meters", "trunk", "block", "again", "dozens", "pile", "foundation", "upside-down", "forest",
    "rots", "underwater", "air", "wet", "forever", "dry", "flat", "beams", "steep", "ladder", "sofa", "hook",
    "window", "swings", "smashes", "leaning", "purpose", "fall", "soup", "hundreds", "royal", "13,659",
    "congratulations", "amsterdam", "stairs", "beams", "saw", "drops", "rot",
}

HL = set(CONFIG["highlight"]) if CONFIG else HL_DEFAULT
FUNCTION = {"a", "an", "the", "of", "to", "in", "on", "and", "but", "so", "you", "your", "is", "it", "by", "with", "from", "are", "this", "that", "be", "if"}

def key(t):
    return re.sub(r"[^a-z0-9,\-$×. ]", "", t.lower()).strip(",.").replace("…", "")

chunks = []
cur = []
def flush():
    if cur:
        chunks.append(list(cur))
        cur.clear()
for w in words:
    cur.append(w)
    text = " ".join(x["text"] for x in cur)
    ends_clause = bool(re.search(r"[.,:?!]$|\.\.\.$", w["text"]))
    dangling = key(w["text"]) in FUNCTION and len(cur) < 4 and len(text) < 19
    if ends_clause or ((len(cur) >= 3 or len(text) >= 15) and not dangling):
        flush()
flush()

out = []
for c in chunks:
    hl_idx = [i for i, w in enumerate(c) if key(w["text"]) in HL]
    pick = hl_idx[-1] if hl_idx else -1
    parts = []
    for i, w in enumerate(c):
        t = w["text"].rstrip(",:")
        if t.endswith("..."):
            t = t[:-3] + "…"
        parts.append(f"*{t}*" if i == pick else t)
    out.append({"start": round(max(0, c[0]["start"] - 0.04), 3), "end": c[-1]["end"], "text": " ".join(parts)})

with open(out_path, "w") as f:
    f.write("// Generated by scripts/make-captions.py from the ElevenLabs voice-over. Times in seconds.\n")
    f.write("export const VOICE_DURATION = %s;\n\n" % (CONFIG["duration"] if CONFIG else 94.354))
    f.write("export type Word = { text: string; start: number; end: number };\n")
    f.write("export const WORDS: Word[] = " + json.dumps(words, indent=0).replace("\n", "") + ";\n\n")
    f.write("export type CaptionChunk = { start: number; end: number; text: string };\n")
    f.write("export const CAPTIONS: CaptionChunk[] = [\n")
    for c in out:
        f.write("  " + json.dumps(c) + ",\n")
    f.write("];\n")
print(len(words), "words,", len(out), "caption chunks")
